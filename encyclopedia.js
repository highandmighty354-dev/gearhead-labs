/* Gearhead Labs — Engineering Encyclopedia page (Issue #23).
   Data: catalog/gearhead-encyclopedia.json (generated by catalog/build-encyclopedia.js; validated by catalog/check-encyclopedia.js).
   Search, filters and sorting are pure functions on that data (window.GHEnc, also used by the tests). The page only reads public
   data and links into the app through index.html?calc=<id> / ?lab=<key>, so the app's own Premium checks decide what opens. */
(function () {
  'use strict';
  const DATA_URL = 'catalog/gearhead-encyclopedia.json?v=20261026-0100';

  /* ---------- text normalisation (shared by search, sort and letters) ---------- */
  const fold = s => String(s == null ? '' : s).normalize('NFKD').replace(/[̀-ͯ]/g, '').toLowerCase();
  const words = s => fold(s).replace(/[^\p{L}\p{N}]+/gu, ' ').trim();
  const compact = s => words(s).replace(/ /g, '');
  const sortKey = s => String(s).normalize('NFKD').replace(/[^\p{L}\p{N} ]+/gu, ' ').replace(/\s+/g, ' ').trim().toLowerCase();
  const cmpAZ = (a, b) => sortKey(a.term).localeCompare(sortKey(b.term), 'en') || a.id.localeCompare(b.id);
  const TYPE_LABEL = { concept: 'Concept', abbreviation: 'Abbreviation', calculator: 'Calculator' };
  const REL_LABEL = { broader: 'Broader concept', narrower: 'Narrower concept', prerequisite: 'Needs first', 'prerequisite-for': 'Needed for', related: 'Related', 'not-equivalent': 'Not the same as' };

  /* ---------- index: one record per entry, with the searchable fields normalised once ---------- */
  function buildIndex(data) {
    const byId = new Map(data.entries.map(e => [e.id, e]));
    const ambiguous = new Map((data.ambiguous || []).map(a => [words(a.term), a]));
    const recs = data.entries.map(e => {
      const names = [e.term];
      const aliases = (e.aliases || []).concat(e.abbreviations || []);
      if (e.type === 'abbreviation') e.expands_to.forEach(t => { const c = byId.get(t); if (c) aliases.push(c.term); });
      const ids = e.type === 'calculator' ? [e.calculator].concat(e.former_ids || []) : [];
      const tech = [];
      if (e.formula) { e.formula.inputs.forEach(x => tech.push(x)); e.formula.outputs.forEach(o => { tech.push(o.name || ''); tech.push(o.unit || ''); }); }
      (e.units || []).forEach(u => tech.push(u));
      const text = [e.definition, e.distinctions, e.description].filter(Boolean).join(' ');
      const related = [];
      (e.related || []).forEach(r => { const t = byId.get(r.to); if (t) related.push(t.term); });
      (e.concepts || []).forEach(c => { const t = byId.get(c); if (t) related.push(t.term); });
      (e.calculators || []).forEach(c => { const t = byId.get('calc.' + c); if (t) related.push(t.term); });
      const sections = (e.sections || []).map(s => s.category + ' ' + s.lab);
      const f = { term: words(e.term), termC: compact(e.term), aliases: aliases.map(words), aliasesC: aliases.map(compact), ids: ids.map(words), idsRaw: ids,
        tech: words(tech.join(' ')), text: words(text), related: words(related.join(' ')), sections: words(sections.join(' ')) };
      f.all = ' ' + [f.term, f.aliases.join(' '), f.ids.join(' '), f.tech, f.text, f.related, f.sections].join(' ');
      f.nameW = [f.term].concat(f.aliases, f.ids).map(n => n.split(' '));
      return { e, f };
    });
    return { data, recs, byId, ambiguous };
  }

  /* relevance: the strongest field the query matches. Every query word must start a word somewhere in the entry (AND), or the
     whole query, without spaces, must occur in the name, an alias or an id ("ujoint" finds "U-Joint"). */
  const has = (hay, t) => (' ' + hay).includes(' ' + t);
  /* the query without spaces equals whole consecutive words of a name, starting at a word ("ujoint" = "u" + "joint"; "rod" never
     matches inside "hp aero drag") */
  const joined = (ws, qc) => ws.some((_, i) => { let s = ''; for (let j = i; j < ws.length && s.length < qc.length; j++) s += ws[j]; return s.startsWith(qc); });
  const joinedAny = (lists, qc) => lists.some(w => joined(w, qc));
  function score(r, q) {
    const qw = words(q), qc = compact(q);
    if (!qw) return 0;
    const toks = qw.split(' ');
    const f = r.f;
    if (!toks.every(t => f.all.includes(' ' + t)) && !joinedAny(f.nameW, qc)) return 0;
    if (f.term === qw || f.termC === qc) return 100;
    if (f.aliases.includes(qw) || f.aliasesC.includes(qc)) return 90;
    if (f.idsRaw.some(id => id.toLowerCase() === String(q).trim().toLowerCase()) || f.ids.includes(qw)) return 85;
    if (f.term.startsWith(qw) || f.termC.startsWith(qc)) return 70;
    if (f.aliases.some(a => a.startsWith(qw))) return 60;
    if (toks.every(t => has(f.term, t)) || joined(f.nameW[0], qc)) return 50;
    if (toks.every(t => f.aliases.some(a => has(a, t))) || joinedAny(f.nameW.slice(1, 1 + f.aliases.length), qc)) return 45;
    if (toks.every(t => f.ids.some(a => has(a, t)))) return 35;
    if (toks.every(t => has(f.tech, t))) return 25;
    if (toks.every(t => has(f.text, t))) return 15;
    if (toks.every(t => has(f.related, t))) return 12;
    return 10;
  }

  /* query = { q, type, lab, category, tier, sort } -> { results, sort, notices } */
  function query(index, opts) {
    const o = Object.assign({ q: '', type: '', lab: '', category: '', tier: '', sort: '' }, opts || {});
    const modes = index.data.sort_modes;
    let sort = o.sort || (words(o.q) ? 'relevance' : 'az');
    const notices = [];
    if (sort !== 'relevance' && !(modes[sort] && modes[sort].supported)) {
      notices.push({ kind: 'sort', text: modes[sort] ? `“${sortLabel(sort)}” is not available: ${modes[sort].reason} Showing A–Z.` : 'Unknown sort; showing A–Z.' });
      sort = 'az';
    }
    if (sort === 'relevance' && !words(o.q)) sort = 'az';
    let res = index.recs.map(r => ({ r, s: words(o.q) ? score(r, o.q) : 1 })).filter(x => x.s > 0);
    res = res.filter(({ r: { e } }) => (!o.type || e.type === o.type)
      && (!o.lab || (e.sections || []).some(s => s.lab === o.lab) || (e.type === 'abbreviation' && e.expands_to.some(t => (index.byId.get(t).sections || []).some(s => s.lab === o.lab))))
      && (!o.category || (e.sections || []).some(s => s.category === o.category) || (e.type === 'abbreviation' && e.expands_to.some(t => (index.byId.get(t).sections || []).some(s => s.category === o.category))))
      && (!o.tier || (e.type === 'calculator' && e.tier === o.tier)));
    if (sort === 'relevance') res.sort((a, b) => b.s - a.s || cmpAZ(a.r.e, b.r.e));
    else if (sort === 'za') res.sort((a, b) => -cmpAZ(a.r.e, b.r.e));
    else res.sort((a, b) => cmpAZ(a.r.e, b.r.e));
    const amb = index.ambiguous.get(words(o.q));
    if (amb) notices.push({ kind: 'ambiguous', text: `“${amb.term}” can mean more than one thing. ${amb.note}` });
    return { results: res.map(x => x.r.e), sort, notices };
  }
  const SORT_LABELS = { relevance: 'Best match', az: 'A–Z', za: 'Z–A', 'most-used': 'Most used', 'least-used': 'Least used', 'most-popular': 'Most popular', 'recently-added': 'Recently added', 'recently-updated': 'Recently updated' };
  const sortLabel = k => SORT_LABELS[k] || k;

  window.GHEnc = { buildIndex, query, score, words, compact, sortKey };

  /* ---------- page ---------- */
  if (typeof document === 'undefined' || !document.getElementById('enc')) return;
  const $ = id => document.getElementById(id);
  const esc = s => String(s == null ? '' : s).replace(/[&<>"']/g, m => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[m]));
  let IX = null;
  const state = { q: '', type: '', lab: '', category: '', tier: '', sort: '', entry: '' };

  function readURL() {
    const p = new URLSearchParams(location.search);
    for (const k of Object.keys(state)) state[k] = p.get(k === 'category' ? 'cat' : k) || '';
  }
  function writeURL(push) {
    const p = new URLSearchParams();
    for (const [k, v] of Object.entries(state)) if (v) p.set(k === 'category' ? 'cat' : k, v);
    const url = location.pathname + (p.toString() ? '?' + p : '');
    if (url !== location.pathname + location.search) history[push ? 'pushState' : 'replaceState'](null, '', url);
  }
  const calcHref = id => `index.html?calc=${encodeURIComponent(id)}`;
  const entryHref = id => { const p = new URLSearchParams(location.search); p.set('entry', id); return '?' + p; };
  const labLabel = k => ((IX.data.facets.labs.find(l => l.key === k) || {}).label) || k;
  const catLabel = c => c.replace(/^([A-Z]+) \/ /, '$1 · ').toLowerCase().replace(/(^|[\s·(&/-])([a-z])/g, (m, a, b) => a + b.toUpperCase()).replace(/\bEv\b/g, 'EV').replace(/\bNvh\b/g, 'NVH').replace(/\bHvac\b/g, 'HVAC');

  function controls() {
    const f = IX.data.facets;
    $('f-lab').innerHTML = '<option value="">All labs</option>' + f.labs.map(l => `<option value="${esc(l.key)}">${esc(l.label)}</option>`).join('');
    $('f-cat').innerHTML = '<option value="">All sections</option>' + f.categories.map(c => `<option value="${esc(c.name)}">${esc(catLabel(c.name))}</option>`).join('');
    const modes = IX.data.sort_modes;
    $('f-sort').innerHTML = '<option value="">Best match / A–Z</option>' + Object.keys(SORT_LABELS).filter(k => k !== 'relevance').map(k => {
      const m = modes[k] || { supported: false, reason: 'not defined' };
      return `<option value="${k}"${m.supported ? '' : ' disabled'}>${esc(sortLabel(k))}${m.supported ? '' : ' — not available yet'}</option>`;
    }).join('');
    $('sort-note').textContent = 'Most used, most popular and recently added/updated are not available: ' + modes['most-used'].reason + ' ' + modes['recently-added'].reason;
  }
  function syncControls() {
    $('q').value = state.q; $('f-type').value = state.type; $('f-lab').value = state.lab; $('f-cat').value = state.category; $('f-tier').value = state.tier; $('f-sort').value = state.sort;
  }

  const KIND_LABEL = { analyzer: 'Analyzer', workbench: 'Workbench' };
  function badge(e) {
    const t = `<span class="b b-${e.type}">${e.type === 'calculator' && KIND_LABEL[e.kind] ? KIND_LABEL[e.kind] : TYPE_LABEL[e.type]}</span>`;
    return t + (e.type === 'calculator' && e.tier === 'premium' ? '<span class="b b-prem">Premium</span>' : '');
  }
  function line(e) {
    if (e.type === 'abbreviation') return 'Stands for ' + e.expands_to.map(t => esc(IX.byId.get(t).term)).join(' · ');
    const s = e.definition || e.description || '';
    return esc(s.length > 140 ? s.slice(0, 137).replace(/\s+\S*$/, '') + '…' : s);
  }

  function renderList() {
    const r = query(IX, state);
    const n = r.results.length;
    $('count').textContent = `${n} ${n === 1 ? 'entry' : 'entries'}` + (state.q ? ` for “${state.q}”` : '') + (r.sort === 'relevance' ? ' · best match first' : r.sort === 'za' ? ' · Z–A' : ' · A–Z');
    $('notices').innerHTML = r.notices.map(x => `<p class="notice notice-${x.kind}" role="status">${esc(x.text)}</p>`).join('');
    const present = new Set(r.results.map(e => e.letter));
    const letters = 'ABCDEFGHIJKLMNOPQRSTUVWXYZ#'.split('');
    const grouped = r.sort !== 'relevance';
    $('letters').innerHTML = letters.map(L => `<button type="button" class="L" data-l="${L}" ${grouped && present.has(L) ? '' : 'disabled'} aria-label="Jump to ${L === '#' ? 'numbers and symbols' : L}">${L}</button>`).join('');
    if (!n) {
      $('list').innerHTML = `<div class="empty" role="status"><p><strong>No entries match.</strong></p><p>${state.q ? `Nothing in the encyclopedia matches “${esc(state.q)}”` : 'No entries match these filters'}${(state.type || state.lab || state.category || state.tier) ? ' with the filters set' : ''}.</p>` +
        `<p><button type="button" id="clear-all">Clear search and filters</button></p></div>`;
      return r;
    }
    let html = '', cur = null;
    for (const e of r.results) {
      if (grouped && e.letter !== cur) { if (cur !== null) html += '</ul>'; cur = e.letter; html += `<h2 class="grp" id="letter-${cur === '#' ? 'num' : cur}" tabindex="-1">${cur}</h2><ul class="items">`; }
      else if (!grouped && cur === null) { cur = ''; html += '<ul class="items">'; }
      html += `<li><a class="item${state.entry === e.id ? ' sel' : ''}" href="${esc(entryHref(e.id))}" data-id="${esc(e.id)}"><span class="t">${esc(e.term)}</span>${badge(e)}<span class="d">${line(e)}</span></a></li>`;
    }
    html += '</ul>';
    $('list').innerHTML = html;
    return r;
  }

  function linkCalc(id, label) {
    const e = IX.byId.get('calc.' + id);
    return `<li><a href="${esc(entryHref('calc.' + id))}" data-id="calc.${esc(id)}">${esc(label || (e ? e.term : id))}</a>${e && e.tier === 'premium' ? ' <span class="b b-prem">Premium</span>' : ''} · <a class="open" href="${esc(calcHref(id))}" target="_top">Open calculator →</a></li>`;
  }
  function sectionsHTML(e) {
    if (!(e.sections || []).length) return '';
    return `<h3>Find it in</h3><ul class="secs">${e.sections.map(s => {
      const lab = IX.data.facets.labs.find(l => l.key === s.lab) || {};
      return `<li>${lab.route ? `<a href="${esc(lab.route)}" target="_top">${esc(lab.label)}</a>` : esc(lab.label || s.lab)} › <a href="?cat=${encodeURIComponent(s.category)}" data-cat="${esc(s.category)}">${esc(catLabel(s.category))}</a></li>`;
    }).join('')}</ul>`;
  }
  function sourcesHTML(e) {
    if (!(e.sources || []).length) return '';
    return `<h3>Sources</h3><ul class="srcs">${e.sources.map(s => `<li><a href="${esc(s.url)}" target="_blank" rel="noopener noreferrer">${esc(s.title)}</a> <span class="muted">— ${esc([s.publisher, s.author, s.date].filter(Boolean).join(', '))}</span>${s.supports ? `<br><span class="small muted">Supports: ${esc(s.supports)}</span>` : ''}</li>`).join('')}</ul>`;
  }
  function reviewHTML(e) {
    const st = e.review.status;
    const r = e.review;
    const txt = st === 'generated' ? 'Generated from the calculator catalogue and the calculator page; not separately reviewed.'
      : st === 'draft-unreviewed' ? 'Draft definition, not yet reviewed. No source cited yet.'
        : st === 'citation-partial' ? `Partly checked against the sources below (${esc(r.checked)}); not yet approved by a reviewer.`
          : st === 'citation-verified' ? `Checked against the sources below (${esc(r.checked)}); not yet approved by a reviewer.`
            : `Reviewed by ${esc(r.reviewer)} on ${esc(r.verified)}.`;
    const inc = (e.incomplete || []).filter(x => !(st === 'draft-unreviewed' && x === 'sources'));
    const notes = (st === 'citation-partial' || st === 'draft-unreviewed') && r.notes ? ` <span class="rev-notes">Open question: ${esc(r.notes)}</span>` : '';
    return `<p class="rev rev-${st}">${txt}${notes}${inc.length ? ' Missing: ' + inc.map(esc).join(', ') + '.' : ''}</p>`;
  }

  function renderEntry() {
    const box = $('entry');
    const e = state.entry && IX.byId.get(state.entry);
    document.body.classList.toggle('has-entry', !!e);
    if (!e) { box.innerHTML = state.entry ? `<div class="empty" role="status"><p><strong>Entry not found.</strong></p><p>There is no entry “${esc(state.entry)}”. It may have been renamed.</p></div>` : '<div class="hint"><p>Search or pick an entry to see its definition, the calculators that use it and related concepts.</p></div>'; return; }
    let h = `<button type="button" class="back" id="back">← All entries</button><h2 id="entry-title" tabindex="-1">${esc(e.term)}</h2><p class="badges">${badge(e)}</p>`;
    if (e.type === 'abbreviation') {
      h += `<p>Abbreviation of:</p><ul class="rel">${e.expands_to.map(t => { const c = IX.byId.get(t); return `<li><a href="${esc(entryHref(t))}" data-id="${esc(t)}">${esc(c.term)}</a>${c.definition ? ` — <span class="note">${esc(c.definition)}</span>` : ''}</li>`; }).join('')}</ul>`;
      if (e.note) h += `<p class="notice notice-ambiguous">${esc(e.note)}</p>`;
    }
    if (e.type === 'concept') {
      if (e.definition) h += `<p class="def">${esc(e.definition)}</p>`;
      if (e.distinctions) h += `<p class="dist"><strong>Watch out:</strong> ${esc(e.distinctions)}</p>`;
      const syn = e.aliases.concat(e.abbreviations);
      if (syn.length) h += `<h3>Also called</h3><p class="syn">${syn.map(esc).join(' · ')}</p>`;
      if (e.units.length) h += `<h3>Units</h3><p>${e.units.map(esc).join(', ')}</p>`;
      if (e.calculators.length) h += `<h3>Calculate it</h3><ul class="calcs">${e.calculators.map(id => linkCalc(id)).join('')}</ul>`;
      if (e.related.length) h += `<h3>Related concepts</h3><ul class="rel">${e.related.map(r => `<li><span class="rt">${esc(REL_LABEL[r.type] || r.type)}</span> <a href="${esc(entryHref(r.to))}" data-id="${esc(r.to)}">${esc(IX.byId.get(r.to).term)}</a>${r.note ? ` — <span class="note">${esc(r.note)}</span>` : ''}</li>`).join('')}</ul>`;
    }
    if (e.type === 'calculator') {
      if (e.description) h += `<p class="def">${esc(e.description)}</p>`;
      else h += `<p class="muted">${e.tier === 'premium' ? 'A Premium tool. Its details are shown inside Gearhead Labs Premium.' : 'No description yet.'}</p>`;
      if (e.formula) h += `<h3>Inputs</h3><p>${e.formula.inputs.map(esc).join(' · ')}</p><h3>Results</h3><p>${e.formula.outputs.map(o => esc(o.name || 'Result') + (o.unit ? ` <span class="u">(${esc(o.unit)})</span>` : '')).join(' · ')}</p>`;
      h += `<p class="cta"><a class="btn" href="${esc(calcHref(e.calculator))}" target="_top">Open ${esc(e.term)} →</a>${e.tier === 'premium' ? ' <span class="muted">Premium sign-in required</span>' : ''}</p>`;
      if (e.concepts.length) h += `<h3>Concepts</h3><ul class="rel">${e.concepts.map(c => `<li><a href="${esc(entryHref(c))}" data-id="${esc(c)}">${esc(IX.byId.get(c).term)}</a></li>`).join('')}</ul>`;
      if (e.former_ids.length) h += `<h3>Former links</h3><p class="muted">${e.former_ids.map(esc).join(', ')} (still open this calculator)</p>`;
      h += `<p class="muted small">ID: <code>${esc(e.calculator)}</code></p>`;
    }
    h += sectionsHTML(e) + sourcesHTML(e) + reviewHTML(e);
    box.innerHTML = h;
  }

  function update(opts) {
    renderList(); renderEntry();
    if (opts && opts.focusEntry) { const t = $('entry-title'); if (t) t.focus(); }
    document.title = (state.entry && IX.byId.get(state.entry) ? IX.byId.get(state.entry).term + ' — ' : '') + 'Engineering Encyclopedia | Gearhead Labs';
  }

  function wire() {
    let timer = null;
    $('q').addEventListener('input', () => { clearTimeout(timer); timer = setTimeout(() => { state.q = $('q').value.trim(); writeURL(false); renderList(); }, 80); });
    for (const [id, k] of [['f-type', 'type'], ['f-lab', 'lab'], ['f-cat', 'category'], ['f-tier', 'tier'], ['f-sort', 'sort']]) $(id).addEventListener('change', () => { state[k] = $(id).value; writeURL(false); renderList(); });
    document.addEventListener('click', ev => {
      const a = ev.target.closest('a[data-id], a[data-cat], button.L, #clear-all, #back');
      if (!a || ev.metaKey || ev.ctrlKey || ev.shiftKey) return;
      if (a.id === 'clear-all') { Object.assign(state, { q: '', type: '', lab: '', category: '', tier: '', sort: '' }); syncControls(); writeURL(false); update(); $('q').focus(); return; }
      if (a.id === 'back') { state.entry = ''; writeURL(true); update(); const s = document.querySelector('.item'); if (s) s.focus(); return; }
      if (a.matches('button.L')) { const g = $('letter-' + (a.dataset.l === '#' ? 'num' : a.dataset.l)); if (g) { g.scrollIntoView({ block: 'start' }); g.focus({ preventScroll: true }); } return; }
      ev.preventDefault();
      if (a.dataset.cat) { state.category = a.dataset.cat; state.entry = ''; syncControls(); writeURL(true); update(); return; }
      state.entry = a.dataset.id; writeURL(true); update({ focusEntry: true });
    });
    document.addEventListener('keydown', ev => {
      if (ev.key === '/' && document.activeElement !== $('q') && !/INPUT|SELECT|TEXTAREA/.test(document.activeElement.tagName)) { ev.preventDefault(); $('q').focus(); }
      else if (ev.key === 'Escape') {
        if (document.activeElement === $('q') && $('q').value) { $('q').value = ''; state.q = ''; writeURL(false); renderList(); }
        else if (state.entry) { state.entry = ''; writeURL(true); update(); }
      }
    });
    window.addEventListener('popstate', () => { readURL(); syncControls(); update(); });
  }

  fetch(DATA_URL).then(r => { if (!r.ok) throw new Error('HTTP ' + r.status); return r.json(); }).then(data => {
    IX = buildIndex(data); window.GHEnc.index = IX;
    /* phones: the filters start folded so the list gets the screen; opened when a filter is already set by the address */
    if (window.matchMedia && matchMedia('(max-width:760px)').matches) { const p = new URLSearchParams(location.search); $('fbox').open = ['type', 'lab', 'cat', 'tier', 'sort'].some(k => p.get(k)); }
    controls(); readURL(); syncControls(); wire(); update({ focusEntry: !!state.entry });
    $('enc').setAttribute('aria-busy', 'false');
    $('stats').textContent = `${data.counts.concepts} concepts · ${data.counts.abbreviations} abbreviations · ${data.counts.calculators} tools`;
  }).catch(err => {
    $('enc').setAttribute('aria-busy', 'false');
    $('list').innerHTML = `<div class="empty" role="alert"><p><strong>The encyclopedia could not be loaded.</strong></p><p>${esc(err.message)}. The calculators still work: <a href="index.html" target="_top">open Gearhead Labs</a>.</p></div>`;
  });
})();
